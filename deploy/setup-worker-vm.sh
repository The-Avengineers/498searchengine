#!/usr/bin/env bash
# Sets up a GCP VM as a search worker node.
#
# Usage:
#   ./setup-worker-vm.sh <NODE_ID> <NUM_PEERS> <PEER_0_IP> [PEER_1_IP ...]
#
# Arguments:
#   NODE_ID    -- this node's index (0-based integer). The coordinator is always 0.
#                 Workers start at 1.
#   NUM_PEERS  -- total number of nodes in the cluster (coordinator + workers).
#   PEER_N_IP  -- internal IP of each peer, in order (0, 1, 2, ...).
#                 List ALL nodes including the coordinator, in ID order.
#                 Your own IP is ignored but must still be present in the right position.
#
# Example (3-node cluster, this machine is worker 2):
#   ./setup-worker-vm.sh 2 3 10.128.0.2 10.128.0.5 10.128.0.9
#
# Prerequisites:
#   - Ubuntu 22.04+ or Debian 12+
#   - SSH public key at ~/.ssh/id_ed25519.pub (for container SSH access)
#   - Index shards pre-copied to AVENGINE_HOST_INDEX_DIR (default: ~/avengine-index)
#   - TCP port 47857 open inbound from all other peer IPs in your GCP firewall
#
# GCP firewall rule (run once per project, adjust source IPs):
#   gcloud compute firewall-rules create avengine-peer \
#     --allow tcp:47857 \
#     --source-ranges=PEER_0_IP/32,PEER_1_IP/32,...

set -euo pipefail

REPO_URL="https://github.com/The-Avengineers/498searchengine.git"
REPO_DIR="${HOME}/498searchengine"
INDEX_DIR="${AVENGINE_HOST_INDEX_DIR:-${HOME}/avengine-index}"
COMPOSE_FILE="${REPO_DIR}/infra/deploy/docker-compose.search.yml"

# ── argument parsing ──────────────────────────────────────────────────────────

if [[ $# -lt 3 ]]; then
  echo "Usage: $0 <NODE_ID> <NUM_PEERS> <PEER_0_IP> [PEER_1_IP ...]" >&2
  echo "  NODE_ID   = this node's ID (coordinator=0, workers=1,2,...)" >&2
  echo "  NUM_PEERS = total nodes including coordinator" >&2
  echo "  PEER_N_IP = internal IPs of all nodes in ID order" >&2
  exit 1
fi

NODE_ID="$1"
NUM_PEERS="$2"
shift 2
PEER_IPS=("$@")

if [[ "${#PEER_IPS[@]}" -ne "${NUM_PEERS}" ]]; then
  echo "Error: expected ${NUM_PEERS} peer IP(s) but got ${#PEER_IPS[@]}" >&2
  exit 1
fi

if [[ "${NODE_ID}" -eq 0 ]]; then
  echo "Error: NODE_ID 0 is reserved for the coordinator. Workers start at 1." >&2
  exit 1
fi

echo "==> Setting up avengine worker (NODE_ID=${NODE_ID}, NUM_PEERS=${NUM_PEERS})"

# ── install docker ────────────────────────────────────────────────────────────

if ! command -v docker &>/dev/null; then
  echo "==> Installing Docker..."
  curl -fsSL https://get.docker.com | sudo sh
  sudo usermod -aG docker "${USER}"
  echo "NOTE: You may need to log out and back in for Docker group membership to take effect."
  echo "      Re-run this script after logging back in if the next step fails."
fi

# ── clone / update repo ───────────────────────────────────────────────────────

if [[ -d "${REPO_DIR}/.git" ]]; then
  echo "==> Updating repo at ${REPO_DIR}..."
  git -C "${REPO_DIR}" pull --ff-only
else
  echo "==> Cloning repo to ${REPO_DIR}..."
  git clone "${REPO_URL}" "${REPO_DIR}"
fi

# ── ensure index directory exists ────────────────────────────────────────────

if [[ ! -d "${INDEX_DIR}" ]]; then
  echo "==> Creating empty index directory at ${INDEX_DIR}"
  echo "    (Copy your .sfi index shards here before starting the container.)"
  mkdir -p "${INDEX_DIR}"
fi

# ── write env file ────────────────────────────────────────────────────────────

ENV_FILE="${REPO_DIR}/.env.search"
echo "==> Writing ${ENV_FILE}..."

{
  echo "# Auto-generated by setup-worker-vm.sh — edit as needed"
  echo "SEARCH_ROLE=worker"
  echo "NODE_ID=${NODE_ID}"
  echo "NUM_PEERS=${NUM_PEERS}"
  echo "AVENGINE_HOST_INDEX_DIR=${INDEX_DIR}"

  # SSH pubkey (optional but useful for container access)
  PUBKEY_FILE=""
  for candidate in "${HOME}/.ssh/id_ed25519.pub" "${HOME}/.ssh/id_rsa.pub"; do
    if [[ -f "${candidate}" ]]; then
      PUBKEY_FILE="${candidate}"
      break
    fi
  done
  if [[ -n "${PUBKEY_FILE}" ]]; then
    echo "AVENGINE_SSH_PUBKEY=$(cat "${PUBKEY_FILE}")"
  fi

  # Peer addresses
  for i in "${!PEER_IPS[@]}"; do
    echo "PEER_${i}_ADDR=${PEER_IPS[$i]}"
  done
} > "${ENV_FILE}"

echo "    Written: SEARCH_ROLE=worker NODE_ID=${NODE_ID} NUM_PEERS=${NUM_PEERS}"
for i in "${!PEER_IPS[@]}"; do
  echo "             PEER_${i}_ADDR=${PEER_IPS[$i]}"
done

# ── build and start container ─────────────────────────────────────────────────

echo "==> Building and starting avengine-search container..."
docker compose \
  -f "${COMPOSE_FILE}" \
  --env-file "${ENV_FILE}" \
  up -d --build

echo ""
echo "==> Worker node ${NODE_ID} is running."
echo "    Logs:    docker logs -f avengine-search"
echo "    Shell:   ssh -p 2222 engine@localhost"
echo "    Index:   copy .sfi shards to ${INDEX_DIR}"
echo ""
echo "    Make sure TCP port 47857 is open inbound from all peer IPs in your GCP firewall."
